"""
Generate the setup rule table ``autoarray/config/setup_rules.yaml`` from the
designation decisions of a PyAutoPulse checkout.

Usage::

    python -m autoarray.setup.generate_rules --pulse <path to PyAutoPulse>
    python -m autoarray.setup.generate_rules --pulse <path to PyAutoPulse> --check

The first form rewrites the table. ``--check`` writes nothing and exits non-zero when
the committed table differs from a regeneration (the header's Pulse commit and date
lines are ignored).
"""

import argparse
import datetime
import subprocess
import sys
from pathlib import Path
from typing import List, Optional

import yaml

from autoarray.setup.setup import RULES_PATH

ROW_KEYS = (
    "likelihood",
    "regime",
    "hardware_class",
    "optimal",
    "secondary",
    "decision_id",
    "rule",
)

COMMIT_PREFIX = "# Pulse commit: "
DATE_PREFIX = "# Generated on: "


def rows_from_decisions(decisions_path) -> List[dict]:
    """
    The rule rows of a PyAutoPulse ``decisions.yaml``: one per ``kind: designation``
    decision, sorted by ``(likelihood, regime, hardware_class)``.

    Parameters
    ----------
    decisions_path
        Path to the PyAutoPulse ``decisions.yaml``.
    """
    with open(decisions_path) as f:
        decisions = yaml.safe_load(f)["decisions"]
    rows = [
        {
            "likelihood": d["likelihood"],
            "regime": d["regime"],
            "hardware_class": d["hardware_class"],
            "optimal": d["optimal"],
            "secondary": list(d.get("secondary") or []),
            "decision_id": d["id"],
            "rule": d["rule"],
        }
        for d in decisions
        if d.get("kind") == "designation"
    ]
    return sorted(
        rows, key=lambda r: (r["likelihood"], r["regime"], r["hardware_class"])
    )


def pulse_commit(pulse) -> str:
    """The ``HEAD`` commit of the PyAutoPulse checkout, or ``"unknown"``."""
    try:
        result = subprocess.run(
            ["git", "-C", str(pulse), "rev-parse", "HEAD"],
            capture_output=True,
            text=True,
            check=True,
        )
        return result.stdout.strip()
    except (OSError, subprocess.SubprocessError):
        return "unknown"


def render(rows: List[dict], commit: str, date: Optional[str] = None) -> str:
    """
    The text of the rule table: a provenance header and the ``rules:`` list.

    Parameters
    ----------
    rows
        The rule rows, as from :func:`rows_from_decisions`.
    commit
        The PyAutoPulse commit the rows were read from.
    date
        The generation date (ISO format); defaults to today.
    """
    date = date or datetime.date.today().isoformat()
    header = "\n".join(
        [
            "# Setup rule table: the Pulse-designated optimal compute setup per",
            "# (likelihood, regime, hardware_class), read by aa.Setup.auto.",
            "# Generated by: python -m autoarray.setup.generate_rules --pulse <PyAutoPulse>",
            "# Source: PyAutoPulse decisions.yaml (kind: designation)",
            f"{COMMIT_PREFIX}{commit}",
            f"{DATE_PREFIX}{date}",
            "# Do not hand-edit: change the Pulse decisions and regenerate.",
        ]
    )
    ordered = [{key: row[key] for key in ROW_KEYS} for row in rows]
    body = yaml.safe_dump(
        {"rules": ordered}, sort_keys=False, width=1000, default_flow_style=False
    )
    return f"{header}\n{body}"


def _strip_volatile(text: str) -> str:
    return "\n".join(
        line
        for line in text.splitlines()
        if not line.startswith((COMMIT_PREFIX, DATE_PREFIX))
    )


def generate(pulse, output=RULES_PATH) -> str:
    """
    Regenerate the rule table from a PyAutoPulse checkout and write it to ``output``.

    Returns the written text.
    """
    pulse = Path(pulse)
    text = render(rows_from_decisions(pulse / "decisions.yaml"), pulse_commit(pulse))
    Path(output).write_text(text)
    return text


def check(pulse, output=RULES_PATH) -> bool:
    """
    Whether the table at ``output`` matches a regeneration from ``pulse``, ignoring the
    header's Pulse commit and date lines.
    """
    pulse = Path(pulse)
    expected = render(rows_from_decisions(pulse / "decisions.yaml"), "", "")
    try:
        current = Path(output).read_text()
    except OSError:
        return False
    return _strip_volatile(current) == _strip_volatile(expected)


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(
        description="Generate autoarray/config/setup_rules.yaml from PyAutoPulse."
    )
    parser.add_argument(
        "--pulse", required=True, help="Path to a PyAutoPulse checkout."
    )
    parser.add_argument(
        "--output", default=str(RULES_PATH), help="The rule table to write or check."
    )
    parser.add_argument(
        "--check",
        action="store_true",
        help="Exit non-zero if the table differs from a regeneration; write nothing.",
    )
    args = parser.parse_args(argv)
    if args.check:
        if check(args.pulse, args.output):
            print(f"{args.output} matches {args.pulse}/decisions.yaml.")
            return 0
        print(
            f"{args.output} is out of date with {args.pulse}/decisions.yaml; "
            "regenerate it.",
            file=sys.stderr,
        )
        return 1
    generate(args.pulse, args.output)
    print(f"Wrote {args.output}.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
